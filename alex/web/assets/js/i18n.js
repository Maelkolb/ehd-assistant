const MONTHS = {
  de: ['Januar', 'Februar', 'März', 'April', 'Mai', 'Juni', 'Juli', 'August', 'September',
       'Oktober', 'November', 'Dezember'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September',
       'October', 'November', 'December'],
};

/** '1805-03-11' -> '11. März 1805' / '11 March 1805'; partial dates stay partial. */
export function formatDate(iso) {
  const value = String(iso || '').trim();
  if (value.includes('/')) {
    const [from, to] = value.split('/');
    return from === to ? formatDate(from) : `${formatDate(from)} – ${formatDate(to)}`;
  }
  const match = /^(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?$/.exec(value);
  if (!match) return value;
  const [, year, month, day] = match;
  if (!month) return year;
  const name = MONTHS[language][Number(month) - 1] || month;
  if (!day) return `${name} ${year}`;
  return language === 'en' ? `${Number(day)} ${name} ${year}` : `${Number(day)}. ${name} ${year}`;
}

export function shortMonthDay(iso) {
  const match = /^(\d{4})(?:-(\d{2}))?(?:-(\d{2}))?$/.exec(String(iso || '').trim());
  if (!match || !match[2]) return '';
  const name = (MONTHS[language][Number(match[2]) - 1] || match[2]).slice(0, 3);
  if (!match[3]) return name;
  return language === 'en' ? `${Number(match[3])} ${name}` : `${Number(match[3])}. ${name}`;
}
