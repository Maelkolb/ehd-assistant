let language = document.documentElement.lang === 'en' ? 'en' : 'de';
const listeners = new Set();

export function getLanguage() {
  return language;
}

export function t(key, values) {
  let text = STRINGS[language][key] ?? STRINGS.de[key] ?? key;
  for (const [name, value] of Object.entries(values || {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

/** Apply translations to every element carrying data-i18n* attributes. */
export function translate(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll('[data-i18n-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nLabel));
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
}

export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'de';
  document.documentElement.lang = language;
  try { localStorage.setItem('alex.lang', language); } catch { /* private mode */ }
  document.title = t('app.title');
  translate();
  for (const listener of listeners) listener(language);
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

